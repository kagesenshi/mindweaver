def test_opensearch_resource_defaults():
    """Test default values for OpenSearch resource limits and replicas"""
    model = OpenSearchPlatform(name="test-os", title="Test OpenSearch", project_id=1)
    assert model.replica_count == 1
    assert model.storage_size == "10Gi"
    assert model.cpu_request == 1.0
    assert model.cpu_limit == 2.0
    assert model.mem_request == 2.0
    assert model.mem_limit == 4.0


def test_opensearch_validation():
    """Test validation logic for OpenSearch CPU request vs limit and replica count"""
    # CPU invalid case
    with pytest.raises(ValidationError) as excinfo:
        OpenSearchPlatform.model_validate(
            {
                "name": "test-os",
                "title": "Test OpenSearch",
                "project_id": 1,
                "cpu_request": 3.0,
                "cpu_limit": 2.0,
            }
        )
    assert "CPU request cannot be greater than CPU limit" in str(excinfo.value)

    # Valid odd replica count cases
    for valid_replicas in [1, 3, 5, 7, 9]:
        model = OpenSearchPlatform.model_validate(
            {
                "name": "test-os",
                "title": "Test OpenSearch",
                "project_id": 1,
                "replica_count": valid_replicas,
            }
        )
        assert model.replica_count == valid_replicas

    # Invalid even/out of range replica count cases
    for invalid_replicas in [0, 2, 4, 6, 8, 10, 11]:
        with pytest.raises(ValidationError) as excinfo:
            OpenSearchPlatform.model_validate(
                {
                    "name": "test-os",
                    "title": "Test OpenSearch",
                    "project_id": 1,
                    "replica_count": invalid_replicas,
                }
            )
        assert "Replica count must be an odd number between 1 and 9" in str(excinfo.value)


