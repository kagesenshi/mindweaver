@pytest.mark.asyncio
async def test_opensearch_password_generation(mock_service_dependencies):
    """Test that OpenSearch admin passwords are autogenerated with proper complexity"""
    request, session = mock_service_dependencies
    svc = OpenSearchPlatformService(request, session)

    model = OpenSearchPlatform(
        name="test-os",
        project_id=1,
    )

    assert model.admin_password is None

    # Trigger password generation
    await svc.generate_passwords(model)

    assert model.admin_password is not None
    assert len(model.admin_password) == 18

    # Verify complexity
    def check_complexity(p):
        has_lower = any(c in string.ascii_lowercase for c in p)
        has_upper = any(c in string.ascii_uppercase for c in p)
        has_digit = any(c in string.digits for c in p)
        symbols = "-_.~!@#$%^&*()_+-=[]{}|;:,.<>?"
        has_symbol = any(c in symbols for c in p)
        return has_lower and has_upper and has_digit and has_symbol

    assert check_complexity(model.admin_password)


@pytest.mark.asyncio
async def test_opensearch_render_manifests(mock_service_dependencies):
    """Test that manifests render correctly for single node and multi node setups"""
    request, session = mock_service_dependencies
    svc = OpenSearchPlatformService(request, session)

    # 1. Single node case
    model_single = OpenSearchPlatform(
        name="os-single",
        project_id=1,
        replica_count=1,
        admin_password="pass",
    )
    svc._resolve_namespace = AsyncMock(return_value="test-ns")

    manifests_single = await svc.render_manifests(model_single)
    assert "singleNode: true" in manifests_single
    assert "replicas: 1" in manifests_single
    assert "OPENSEARCH_INITIAL_ADMIN_PASSWORD" in manifests_single
    assert 'value: "pass"' in manifests_single
    
    # Assert security-config Secret is rendered
    assert "kind: Secret" in manifests_single
    assert "name: os-single-security-config" in manifests_single
    assert "internal_users.yml" in manifests_single
    
    # Assert admin certificate is rendered
    assert "name: os-single-admin-tls" in manifests_single
    
    # Assert secret mount and subPath are rendered in the application manifest
    assert "name: os-single-security-config" in manifests_single
    assert "subPath: internal_users.yml" in manifests_single
    assert "path: /usr/share/opensearch/config/opensearch-security/internal_users.yml" in manifests_single
    assert "name: os-single-admin-tls" in manifests_single
    assert "path: /usr/share/opensearch/config/admin-certificates" in manifests_single

    # 2. Multi node scale case
    model_multi = OpenSearchPlatform(
        name="os-multi",
        project_id=1,
        replica_count=3,
        admin_password="pass",
    )
    manifests_multi = await svc.render_manifests(model_multi)
    assert "singleNode: false" in manifests_multi
    assert "replicas: 3" in manifests_multi

